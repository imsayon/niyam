import PDFDocument from "pdfkit";

const palette = { navy: "#152F52", yellow: "#F0BE4E", line: "#D8E0EA", pale: "#F4F7FB", muted: "#59708A" };
const weights = {
  timetable: [1.35, .9, .75, .75, 1.9],
  seating: [1.15, 1.45, .9, .9, 1, .7, .7],
  duties: [1.2, .9, .7, 1, 1.7],
};

export function writeReportPdf(res, { institution, event, kind, run, headers, rows }) {
  const document = new PDFDocument({
    size: "A4",
    margin: 36,
    info: { Title: (institution.shortName || "Institution") + " - " + event.name + " - " + kind },
  });
  document.pipe(res);
  const left = 36;
  const width = document.page.width - 72;
  const proportions = weights[kind] || headers.map(() => 1);
  const sum = proportions.reduce((total, item) => total + item, 0);
  const columns = proportions.map((size) => (width * size) / sum);
  const pageBottom = document.page.height - 45;
  let page = 0;
  let y = 0;

  function pageHeader() {
    page++;
    document.rect(0, 0, document.page.width, 8).fill(palette.yellow);
    document.fillColor(palette.navy).font("Helvetica-Bold").fontSize(20)
      .text(institution.shortName || "Institution", left, 32, { width: width - 110, lineBreak: false });
    document.font("Helvetica-Bold").fontSize(12)
      .text("NIYAM", document.page.width - 145, 39, { width: 109, align: "right", lineBreak: false });
    document.font("Helvetica").fontSize(8).fillColor(palette.muted)
      .text(institution.name || "", left, 60, { width, lineBreak: false });
    document.fillColor(palette.navy).font("Helvetica-Bold").fontSize(13)
      .text(event.name + " / " + kind[0].toUpperCase() + kind.slice(1), left, 82, { width });
    document.font("Helvetica").fontSize(8).fillColor(palette.muted)
      .text(
        (run.publishedAt ? "Published plan" : "Draft plan") +
        "  •  " + rows.length + " records  •  " + run.id.slice(0, 8),
        left, 106, { width },
      );
    y = 130;
    document.rect(left, y, width, 28).fill(palette.navy);
    let x = left;
    headers.forEach((name, index) => {
      document.font("Helvetica-Bold").fontSize(8).fillColor("#FFFFFF")
        .text(String(name), x + 6, y + 9, {
          width: columns[index] - 12, lineBreak: false, ellipsis: true,
        });
      x += columns[index];
    });
    y += 28;
  }
  function footer() {
    document.moveTo(left, document.page.height - 36).lineTo(left + width, document.page.height - 36)
      .strokeColor(palette.line).stroke();
    document.font("Helvetica").fontSize(7).fillColor(palette.muted)
      .text("Generated by Niyam  •  " + (institution.shortName || "Institution"),
        left, document.page.height - 27, { width: width - 70, lineBreak: false })
      .text("Page " + page, left + width - 70, document.page.height - 27,
        { width: 70, align: "right", lineBreak: false });
  }

  pageHeader();
  if (!rows.length) {
    document.font("Helvetica").fontSize(10).fillColor(palette.muted)
      .text("No records available for this report.", left + 10, y + 24);
  }
  rows.forEach((record, rowIndex) => {
    const values = record.map((value) => String(value ?? ""));
    document.font("Helvetica").fontSize(8);
    const lineHeights = values.map((value, index) =>
      document.heightOfString(value, { width: columns[index] - 12, lineGap: 1 }),
    );
    const rowHeight = Math.max(26, ...lineHeights.map((height) => height + 12));
    if (y + rowHeight > pageBottom) {
      footer();
      document.addPage();
      pageHeader();
    }
    if (rowIndex % 2 === 0) document.rect(left, y, width, rowHeight).fill(palette.pale);
    document.moveTo(left, y + rowHeight).lineTo(left + width, y + rowHeight)
      .strokeColor(palette.line).lineWidth(.4).stroke();
    let x = left;
    values.forEach((value, index) => {
      document.font("Helvetica").fontSize(8).fillColor(palette.navy)
        .text(value, x + 6, y + 6, { width: columns[index] - 12, lineGap: 1 });
      x += columns[index];
    });
    y += rowHeight;
  });
  footer();
  document.end();
}
